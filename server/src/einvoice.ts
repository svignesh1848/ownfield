// Step 5e: GST e-invoicing. Builds NIC e-invoice schema v1.1 JSON from a stored invoice / credit note and sends it through a
// provider adapter. Shipped adapters: a TEST mock (fake IRN + QR, clearly marked TEST — never valid for GST) and a GSP stub
// configured via env that refuses to call out. No real IRP/GSP API calls are made anywhere in this codebase.
import type { Express } from "express";
import crypto from "node:crypto";
import QRCode from "qrcode";
import { withTx, type Db } from "./db.js";
import { bad, getCompany } from "./catalog.js";
import { r2, loadInvoice } from "./billing.js";

// UQC (unit quantity code) mapping; anything unknown is sent as OTH.
const UQC: Record<string, string> = { PCS: "PCS", NOS: "NOS", PC: "PCS", EA: "NOS", BOX: "BOX", CASE: "CTN", CTN: "CTN", CARTON: "CTN", PACK: "PAC", PAC: "PAC",
  STRIP: "STR", STR: "STR", BTL: "BTL", BOTTLE: "BTL", KG: "KGS", KGS: "KGS", G: "GMS", GMS: "GMS", L: "LTR", LTR: "LTR", ML: "MLT", M: "MTR", MTR: "MTR", SET: "SET", DOZ: "DOZ", DOZEN: "DOZ", PAIR: "PRS", PRS: "PRS", HRS: "OTH", HOUR: "OTH" };
export const uqc = (u: string) => UQC[String(u || "").toUpperCase()] || "OTH";
const dmy = (iso: string) => `${iso.slice(8, 10)}/${iso.slice(5, 7)}/${iso.slice(0, 4)}`;
const pin = (v: unknown, who: string) => { const s = String(v ?? ""); if (!/^[1-9]\d{5}$/.test(s)) throw bad(`${who} PIN code (6 digits) is required for e-invoicing`); return Number(s); };

/** NIC e-invoice v1.1 payload. B2B only (buyer must have a GSTIN). Throws 400 with a readable reason when data is missing. */
export function nicPayload(inv: any, ref?: { number: string; doc_date: string }) {
  const s = inv.seller, b = inv.buyer;
  if (!s.gstin) throw bad("seller GSTIN missing");
  if (!b.gstin) throw bad("e-invoicing covers B2B only — the outlet has no GSTIN");
  if (!String(s.address || "").trim() || String(s.city || "").trim().length < 3) throw bad("seller address and city are required for e-invoicing");
  if (!String(b.address || "").trim() || String(b.city || "").trim().length < 3) throw bad("outlet address and city are required for e-invoicing");
  const sPin = pin(s.pin, "seller"), bPin = pin(b.pin, "outlet");
  const items = inv.lines.map((l: any, i: number) => {
    const hsn = String(l.hsn || "").replace(/\s/g, "");
    if (!/^\d{4,8}$/.test(hsn)) throw bad(`line ${i + 1}: HSN/SAC of 4–8 digits required`);
    const service = hsn.startsWith("99");
    return { SlNo: String(i + 1), PrdDesc: String(l.description).slice(0, 300), IsServc: service ? "Y" : "N", HsnCd: hsn,
      Qty: Number(l.base_qty), ...(service ? {} : { Unit: uqc(l.uom) }), UnitPrice: r2(Number(l.rate)), TotAmt: r2(Number(l.taxable)), Discount: 0,
      AssAmt: r2(Number(l.taxable)), GstRt: Number(l.gst_rate), IgstAmt: r2(Number(l.igst)), CgstAmt: r2(Number(l.cgst)), SgstAmt: r2(Number(l.sgst)),
      CesRt: 0, CesAmt: 0, CesNonAdvlAmt: 0, StateCesRt: 0, StateCesAmt: 0, StateCesNonAdvlAmt: 0, OthChrg: 0, TotItemVal: r2(Number(l.total)) };
  });
  return {
    Version: "1.1",
    TranDtls: { TaxSch: "GST", SupTyp: "B2B", RegRev: "N", IgstOnIntra: "N" },
    DocDtls: { Typ: inv.kind === "invoice" ? "INV" : "CRN", No: inv.number, Dt: dmy(inv.doc_date) },
    SellerDtls: { Gstin: s.gstin, LglNm: s.name, ...(s.tradeName ? { TrdNm: s.tradeName } : {}), ...(s.phone ? { Ph: String(s.phone).replace(/\D/g, "").slice(-12) } : {}), ...(s.email ? { Em: s.email } : {}), Addr1: String(s.address).slice(0, 100), Loc: s.city, Pin: sPin, Stcd: s.state },
    BuyerDtls: { Gstin: b.gstin, LglNm: b.name, Pos: inv.place_of_supply, Addr1: String(b.address).slice(0, 100), Loc: b.city, Pin: bPin, Stcd: String(b.gstin).slice(0, 2) },
    ItemList: items,
    ValDtls: { AssVal: inv.taxable, CgstVal: inv.cgst, SgstVal: inv.sgst, IgstVal: inv.igst, CesVal: 0, StCesVal: 0, Discount: 0, OthChrg: 0, RndOffAmt: inv.round_off, TotInvVal: inv.total },
    ...(ref ? { RefDtls: { PrecDocDtls: [{ InvNo: ref.number, InvDt: dmy(ref.doc_date) }] } } : {}),
  };
}

export type IrnResult = { irn: string; ackNo: string; ackDt: Date; signedQr: string; test: boolean };
export interface EinvProvider {
  readonly name: string;
  generate(payload: any): Promise<IrnResult>;
  cancel(irn: string, reasonCode: string, remark: string): Promise<{ cancelledAt: Date }>;
}

/** Mock provider: deterministic fake IRN, signed-QR stand-in labelled TEST. Never sent anywhere. */
export class TestProvider implements EinvProvider {
  readonly name = "TEST";
  async generate(p: any): Promise<IrnResult> {
    const fy = p.DocDtls.Dt.slice(6);
    const irn = crypto.createHash("sha256").update(`${p.SellerDtls.Gstin}|${fy}|${p.DocDtls.Typ}|${p.DocDtls.No}|TEST`).digest("hex");
    const ackNo = `TEST${Date.now()}`, ackDt = new Date();
    const body = { TEST: "NOT A VALID E-INVOICE — generated by the OwnField TEST provider", SellerGstin: p.SellerDtls.Gstin, BuyerGstin: p.BuyerDtls.Gstin,
      DocNo: p.DocDtls.No, DocTyp: p.DocDtls.Typ, DocDt: p.DocDtls.Dt, TotInvVal: p.ValDtls.TotInvVal, ItemCnt: p.ItemList.length, MainHsnCode: p.ItemList[0]?.HsnCd, Irn: irn, IrnDt: ackDt.toISOString() };
    const enc = (o: unknown) => Buffer.from(JSON.stringify(o)).toString("base64url");
    return { irn, ackNo, ackDt, signedQr: `${enc({ alg: "none", typ: "TEST" })}.${enc(body)}.TEST-UNSIGNED`, test: true };
  }
  async cancel() { return { cancelledAt: new Date() }; }
}

/** GSP adapter stub. Reads its config from env and validates it, but deliberately makes no network calls. */
export class GspStubProvider implements EinvProvider {
  readonly name = "GSP";
  static readonly ENV = ["EINV_GSP_BASE_URL", "EINV_GSP_CLIENT_ID", "EINV_GSP_CLIENT_SECRET", "EINV_GSP_USERNAME", "EINV_GSP_PASSWORD"] as const;
  constructor(private env: NodeJS.ProcessEnv = process.env) {}
  private check(): never {
    const missing = GspStubProvider.ENV.filter(k => !this.env[k]);
    if (missing.length) throw bad(`GSP provider not configured — set ${missing.join(", ")}`, 503);
    throw bad("GSP adapter is a stub: plug in your GSP's auth + /eicore/v1.03/Invoice calls here. No real API call was made.", 501);
  }
  async generate(): Promise<IrnResult> { return this.check(); }
  async cancel(): Promise<{ cancelledAt: Date }> { return this.check(); }
}

export const providerFor = (name: string, env = process.env): EinvProvider => name === "gsp" ? new GspStubProvider(env) : new TestProvider();
export const CANCEL_REASONS: Record<string, string> = { "1": "Duplicate", "2": "Data entry mistake", "3": "Order cancelled", "4": "Others" };

export async function qrDataUrl(signedQr: string) { return QRCode.toDataURL(signedQr, { errorCorrectionLevel: "M", margin: 1, width: 180 }); }

type Ctx = { app: Express; db: Db; auth: (...r: any[]) => any; tenant: (req: any, res: any) => number | null; wrap: (fn: (req: any, res: any) => Promise<unknown>) => any };
export function registerEinvoiceRoutes({ app, db, auth, wrap }: Ctx) {
  const BILL = ["company_admin", "manager", "distributor"];
  const load = async (req: any) => {
    const cid = req.user.companyId; if (cid == null) throw bad("company-scoped route");
    const { settings } = await getCompany(db, cid);
    if (!settings.features.eInvoice) throw bad("e-invoicing is turned off for this company", 403);
    const inv = await loadInvoice(db, cid, Number(req.params.id));
    if (req.user.role === "distributor" && inv.issuer !== `d${req.user.uid}`) throw bad("invoice not found", 404);
    const ref = inv.ref_invoice_id ? (await db.query("SELECT number, doc_date FROM invoices WHERE id=$1", [inv.ref_invoice_id])).rows[0] : undefined;
    return { cid, settings, inv, ref };
  };
  app.get("/api/invoices/:id/einvoice/json", auth(...BILL), wrap(async (req, res) => {
    const { inv, ref } = await load(req);
    res.attachment(`${inv.number.replace(/\W+/g, "-")}-einvoice.json`).json(nicPayload(inv, ref));
  }));
  app.post("/api/invoices/:id/einvoice", auth(...BILL), wrap(async (req, res) => {
    const { cid, settings, inv, ref } = await load(req);
    if (inv.irn && inv.einv_status === "generated") throw bad("IRN already generated for this document", 409);
    if (inv.einv_status === "cancelled") throw bad("IRN was cancelled — issue a fresh document instead", 409);
    const payload = nicPayload(inv, ref);
    const provider = providerFor(settings.einvoice?.provider || "test");
    const r = await provider.generate(payload);
    await withTx(db, async tx => {
      const u = (await tx.query(`UPDATE invoices SET irn=$1, ack_no=$2, einv_ack_at=$3, signed_qr=$4, einv_status='generated', einv_provider=$5 WHERE id=$6 AND company_id=$7 AND irn IS NULL RETURNING id`,
        [r.irn, r.ackNo, r.ackDt, r.signedQr, provider.name, inv.id, cid])).rows[0];
      if (!u) throw bad("IRN already generated for this document", 409);
    });
    res.status(201).json(await loadInvoice(db, cid, inv.id));
  }));
  app.post("/api/invoices/:id/einvoice/cancel", auth(...BILL), wrap(async (req, res) => {
    const { cid, settings, inv } = await load(req);
    if (inv.einv_status !== "generated") throw bad("no active IRN on this document", 409);
    const code = String(req.body?.reason || ""), remark = String(req.body?.remark || "").trim();
    if (!CANCEL_REASONS[code]) throw bad("reason must be 1 Duplicate, 2 Data entry mistake, 3 Order cancelled or 4 Others");
    if (!remark) throw bad("remark required");
    if (Date.now() - new Date(inv.einv_ack_at).getTime() > 24 * 3600e3) throw bad("IRN can only be cancelled within 24 hours of generation — issue a credit note instead", 409);
    const provider = providerFor(inv.einv_provider === "GSP" ? "gsp" : "test");
    void settings;
    const r = await provider.cancel(inv.irn, code, remark);
    await db.query("UPDATE invoices SET einv_status='cancelled', einv_cancelled_at=$1, einv_cancel_reason=$2 WHERE id=$3 AND company_id=$4 AND einv_status='generated'",
      [r.cancelledAt, `${CANCEL_REASONS[code]}: ${remark}`, inv.id, cid]);
    res.json(await loadInvoice(db, cid, inv.id));
  }));
}

/** HTML block for the printed invoice. */
export async function einvBlock(inv: any) {
  if (!inv.irn) return "";
  const test = inv.einv_provider === "TEST", cancelled = inv.einv_status === "cancelled";
  return `<div style="display:flex;gap:12px;align-items:center;border:2px solid ${test ? "#c00" : "#999"};padding:6px;margin:8px 0">
<img alt="e-invoice QR" src="${await qrDataUrl(inv.signed_qr)}" width="120" height="120"><div>
${test ? `<div style="color:#c00;font-weight:700">TEST E-INVOICE — NOT VALID FOR GST (mock provider)</div>` : ""}
${cancelled ? `<div style="color:#c00;font-weight:700">IRN CANCELLED ${new Date(inv.einv_cancelled_at).toISOString().slice(0, 10)}: ${String(inv.einv_cancel_reason).replace(/[<>&]/g, "")}</div>` : ""}
<div>IRN <code style="word-break:break-all">${inv.irn}</code></div><div>Ack No ${inv.ack_no} · Ack Date ${new Date(inv.einv_ack_at).toLocaleString("en-IN", { timeZone: "Asia/Kolkata" })}</div></div></div>`;
}
